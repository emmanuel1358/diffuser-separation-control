# A license_source pointer for a real (non-self_generated) license must be the
# upstream http(s) URL where the dataset license was confirmed, so a reviewer can
# verify provenance rather than trust a self-declared SPDX id.
_LICENSE_SOURCE_URL_RE = re.compile(r"^https?://", re.IGNORECASE)

