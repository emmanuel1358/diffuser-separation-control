# Permissive licenses cleared for unrestricted commercial use AND derivative
# works. Copyleft / share-alike / non-commercial / research-only licenses are
# intentionally excluded: a task built on such data cannot ship in a commercial
# delivery, and a frontier LLM cannot reliably adjudicate that. Required for
# `ml` tasks, which routinely ship external datasets; mujoco/cfd/structures use
# solver-generated or self-authored data. SPDX identifiers; matched
# case-insensitively (see ``validate_license``).
LICENSES: tuple[str, ...] = (
    "MIT",
    "Apache-2.0",
    "BSD-2-Clause",
    "BSD-3-Clause",
    "ISC",
    "Unlicense",
    "CC0-1.0",
    "CC-BY-4.0",
    "PDDL-1.0",
    "UPL-1.0",
)
LICENSE_REQUIRED_TASK_TYPES: tuple[str, ...] = ("ml",)
# Explicit escape hatch for tasks whose data is generated by the task itself
# (fully synthetic / self-authored data, or no third-party data at all), so no
# external dataset license applies. Accepted everywhere a license is, including
# to satisfy the ml requirement -- but it must be a deliberate choice, not a
# blank, and still needs a license_source justification for ml tasks.
LICENSE_SELF_GENERATED = "self_generated"
# Back-compat alias: "not_applicable" was the previous spelling of the
# self-generated escape hatch. Still accepted so existing tasks keep validating;
# new tasks and docs use "self_generated" (matches the reviewer criterion).
LICENSE_NOT_APPLICABLE = "not_applicable"
# Normalized set of accepted self-generated spellings (see normalize_enum_value).
_SELF_GENERATED_VALUES: frozenset[str] = frozenset(
    {LICENSE_SELF_GENERATED, LICENSE_NOT_APPLICABLE}
)
